function getInitialLanguage(): LanguageCode {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (languageOptions.some((option) => option.code === saved)) return saved as LanguageCode
  } catch {
    // Storage may be unavailable in private browsing; English is the safe default.
  }
  return 'en'
}

interface LanguageContextValue {
  language: LanguageCode
  setLanguage: (language: LanguageCode) => void
  translate: (text: string) => string
  hasTranslation: (text: string) => boolean
}

const LanguageContext = createContext<LanguageContextValue>({
  language: 'en',
  setLanguage: () => undefined,
  translate: (text) => text,
  hasTranslation: () => true,
})

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<LanguageCode>(getInitialLanguage)

  useEffect(() => {
    document.documentElement.lang = language
    const localeMeta = document.querySelector<HTMLMetaElement>('meta[property="og:locale"]')
    if (localeMeta) localeMeta.content = `${language}_PH`
    const websiteJsonLd = document.getElementById('website-jsonld')
    if (websiteJsonLd?.textContent) {
      try {
        const data = JSON.parse(websiteJsonLd.textContent) as { inLanguage?: string }
        data.inLanguage = language
        websiteJsonLd.textContent = JSON.stringify(data)
      } catch {
        // Leave the original structured data in place if it is malformed.
      }
    }
    try {
      localStorage.setItem(STORAGE_KEY, language)
    } catch {
      // The current selection still works for this visit if storage is unavailable.
    }
  }, [language])

  const value = useMemo<LanguageContextValue>(() => {
    const dictionary =
      language === 'en'
        ? undefined
        : { ...messages[language], ...pageCopyMessages[language] }
    return {
      language,
      setLanguage,
      translate: (text) => dictionary?.[text] ?? text,
      hasTranslation: (text) => language === 'en' || Object.hasOwn(dictionary ?? {}, text),
    }
  }, [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  return useContext(LanguageContext)
}
